// server.js

// =============================================================================
// 1. ПОДКЛЮЧЕНИЕ МОДУЛЕЙ (Зависимости)
// =============================================================================

// Express — фреймворк для создания веб-сервера. Нужен, чтобы отдавать HTML-страницу чата.
const express = require('express');

// http — стандартный модуль Node.js. Нужен, потому что Socket.IO требует настоящий HTTP-сервер,
// а не просто приложение Express. Мы обернем Express в http-сервер.
const http = require('http');

// socket.io — библиотека для WebSocket (чат в реальном времени).
const socketIO = require('socket.io');

// path — модуль для работы с путями к файлам. Критически важен, чтобы правильно найти папку public
// на разных операционных системах (Windows vs Linux в облаке).
const path = require('path');

// =============================================================================
// 2. ИНИЦИАЛИЗАЦИЯ СЕРВЕРА
// =============================================================================

// Создаем базовое приложение Express.
const app = express();

// Создаем HTTP-сервер на базе нашего Express-приложения.
// Это обязательно для Socket.IO. Без этой строки чат в реальном времени не заработает.
const server = http.createServer(app);

// Инициализируем Socket.IO, передавая ему наш созданный HTTP-сервер.
// Теперь Socket.IO "слушает" тот же порт, что и сайт.
const io = socketIO(server);

// =============================================================================
// 3. НАСТРОЙКА СТАТИКИ (Раздача файлов сайта)
// =============================================================================

// Эта строка говорит серверу: "Все файлы из папки 'public' отдавай как есть".
// Благодаря этому index.html, style.css и script.js станут доступны по адресу /
//
// ВАЖНО: path.join(__dirname, 'public') собирает правильный путь.
// __dirname — это папка, где лежит этот файл (server.js).
// Мы берем эту папку и добавляем к ней '/public'.
// Это работает и на твоем компьютере, и в Linux-контейнере Railway.
app.use(express.static(path.join(__dirname, 'public')));

// =============================================================================
// 4. ЛОГИКА ЧАТА (Обработчики событий)
// =============================================================================

// Событие 'connection' срабатывает каждый раз, когда кто-то открывает страницу чата.
io.on('connection', (socket) => {
  // socket.id — уникальный ID соединения. Полезен для отладки.
  console.log('Новый пользователь подключился:', socket.id);

  // Слушаем событие 'message', которое отправляет браузер (script.js).
  socket.on('message', (data) => {
    // data — это объект { text: "...", user: "..." }, который прислал клиент.
    console.log('Получено сообщение:', data);

    // io.emit(...) отправляет сообщение ВСЕМ подключенным клиентам.
    // Это создает эффект "чата": ты пишешь — видят все.
    io.emit('message', data);
  });

  // Событие 'disconnect' срабатывает, когда пользователь закрывает вкладку или теряет связь.
  socket.on('disconnect', () => {
    console.log('Пользователь отключился:', socket.id);
    // Здесь можно добавить логику отправки сообщения "Вася вышел", если нужно.
  });
});

// =============================================================================
// 5. ЗАЩИТА ОТ ТИХИХ ПАДЕНИЙ (Критически важно для Railway)
// =============================================================================

// Если сервер попытается занять порт, который уже занят, или случится другая ошибка,
// эта функция поймает её, выведет в логи и принудительно остановит процесс.
// Railway увидит ошибку в логах, а не просто статус "Crashed" без объяснений.
server.on('error', (err) => {
  console.error('Критическая ошибка сервера:', err.message);
  process.exit(1); // Завершаем процесс с кодом ошибки, чтобы Railway понял, что что-то сломалось.
});

// =============================================================================
// 6. ЗАПУСК СЕРВЕРА (Самое важное для облака)
// =============================================================================

// process.env.PORT — переменная окружения, которую дает Railway (например, 8080, 5432 и т.д.).
// || 3000 — запасной вариант. Если переменной нет (например, при запуске локально), берем 3000.
// Никогда не пиши жестко app.listen(3000) в облачных проектах!
const PORT = process.env.PORT || 3000;

server.listen(PORT, () => {
  // Выводим сообщение только о том, что сервер стартовал.
  // Мы УБРАЛИ строку про "localhost", потому что в облаке localhost ничего не значит.
  // Ссылка на чат — это домен Railway, а не localhost.
  console.log(`Сервер успешно запущен на порту ${PORT}`);
});
