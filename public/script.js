/**
 * =============================================================================
 * 1. ПОДКЛЮЧЕНИЕ К СЕРВЕРУ (САМАЯ ВАЖНАЯ ЧАСТЬ)
 * =============================================================================
 * Раньше мы писали просто: const socket = io();
 * Это работало на компьютере, но ломалось на телефонах в разных сетях.
 *
 * Теперь мы делаем так:
 * window.location.origin — это адрес текущей страницы (например, slipper-production.up.railway.app).
 * Мы явно говорим Socket.IO: "Подключайся именно сюда".
 *
 * transports: ['websocket', 'polling'] — КРИТИЧЕСКИ ВАЖНО!
 *   - websocket: быстрая связь в реальном времени.
 *   - polling: обычный HTTP-запрос, который работает почти везде, даже если WebSocket заблокирован.
 *   Если телефон не может сделать WebSocket, он автоматически попробует polling.
 */
const socket = io(window.location.origin, {
  transports: ['websocket', 'polling'],
  reconnectionAttempts: 5,       // Попробовать переподключиться 5 раз, если связь оборвалась
  reconnectionDelay: 1000,      // Ждать 1 секунду перед следующей попыткой
});

/**
 * =============================================================================
 * 2. ПОЛУЧЕНИЕ ЭЛЕМЕНТОВ СТРАНИЦЫ (DOM)
 * =============================================================================
 */
const messagesDiv = document.getElementById('messages');
const chatForm = document.getElementById('chat-form');
const messageInput = document.getElementById('message-input');
const statusBar = document.getElementById('connection-status'); // Блок с ошибкой

/**
 * =============================================================================
 * 3. ФУНКЦИЯ ОТОБРАЖЕНИЯ СООБЩЕНИЙ
 * =============================================================================
 */
function addMessage(text, user = 'Система') {
  const div = document.createElement('div');
  div.className = 'message';
  div.textContent = `${user}: ${text}`;

  messagesDiv.appendChild(div);

  // Автопрокрутка вниз к последнему сообщению
  messagesDiv.scrollTop = messagesDiv.scrollHeight;
}

/**
 * =============================================================================
 * 4. ОБРАБОТКА ОТПРАВКИ СООБЩЕНИЯ
 * =============================================================================
 */
chatForm.addEventListener('submit', (e) => {
  e.preventDefault(); // Отменяем стандартную отправку формы (чтобы страница не перезагружалась)

  const text = messageInput.value.trim();

  if (!text) return; // Если поле пустое, ничего не делаем

  // Отправляем событие 'message' на сервер
  socket.emit('message', {
    text: text,
    user: 'Вы' // В будущем можно сделать поле для ввода имени
  });

  messageInput.value = ''; // Очищаем поле ввода
});

/**
 * =============================================================================
 * 5. СЛУШАТЕЛИ СОБЫТИЙ (Что делать, когда приходит сообщение или ошибка)
 * =============================================================================
 */

// Событие 'message' приходит от сервера (io.emit на сервере)
socket.on('message', (data) => {
  // Скрываем блок ошибки, если вдруг он был виден (значит, связь восстановилась)
  if (statusBar.style.display === 'block') {
    statusBar.style.display = 'none';
  }
  addMessage(data.text, data.user);
});

// Обработка ошибки подключения (самая частая проблема на телефонах)
socket.on('connect_error', (error) => {
  console.error('Ошибка подключения к серверу:', error);

  // Показываем красный блок с ошибкой из index.html
  statusBar.style.display = 'block';

  // Дополнительно пишем в консоль, чтобы ты видел реальную причину
  // Например: "xhr poll error" (нет интернета) или "invalid HTTP status code 502" (ошибка сервера)
});

// Опционально: показать сообщение, когда соединение успешно установлено
socket.on('connect', () => {
  if (statusBar.style.display === 'block') {
    statusBar.style.display = 'none'; // Убираем ошибку, если она была
  }
  // Можно добавить приветствие только при успешном коннекте, если нужно
});

/**
 * =============================================================================
 * 6. ПРИВЕТСТВЕННОЕ СООБЩЕНИЕ
 * =============================================================================
 * Добавляем его сразу, даже до подключения.
 * Если подключение не удастся, пользователь хотя бы увидит, что чат пытается работать.
 */
addMessage('Чат загружается...', 'Система');
